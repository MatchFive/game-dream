const storageKey = 'gamedream.locale';
function safeRead() {
  try { return window.localStorage.getItem(storageKey); } catch { return null; }
}
function safeWrite(value) {
  try { window.localStorage.setItem(storageKey, value); } catch { /* sandbox */ }
}

export let locale = safeRead() === 'en' ? 'en' : 'zh';
if (locale !== 'zh' && locale !== 'en') locale = 'zh';

export function t(key, vars = {}) {
  const table = messages[locale] ?? messages.zh;
  let value = table[key] ?? messages.zh[key] ?? messages.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function applyStatic(root = document) {
  document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  }
  for (const element of root.querySelectorAll('[data-i18n-aria]')) {
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  }
  for (const element of root.querySelectorAll('[data-i18n-value]')) {
    element.value = t(element.dataset.i18nValue);
  }
  for (const element of root.querySelectorAll('[data-locale-toggle]')) {
    element.textContent = locale === 'zh' ? 'EN' : '中';
    element.setAttribute('aria-label', locale === 'zh' ? 'Switch to English' : '切换到中文');
  }
}

export function setLocale(next) {
  locale = next === 'en' ? 'en' : 'zh';
  safeWrite(locale);
  applyStatic();
  window.dispatchEvent(new CustomEvent('localechange', { detail: { locale } }));
}

export function toggleLocale() {
  setLocale(locale === 'zh' ? 'en' : 'zh');
}

export function initLocale() {
  applyStatic();
  for (const button of document.querySelectorAll('[data-locale-toggle]')) {
    button.addEventListener('click', toggleLocale);
  }
}

export function formatDate(value) {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleString(locale === 'zh' ? 'zh-CN' : 'en-US');
}
